package com.marketplace.marketplace.authentication.entity;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.LocalDateTime;
import java.util.Collection;
import java.util.List;
import java.util.UUID;

/**
 * Maps directly to the existing "users" table:
 *
 * CREATE TABLE IF NOT EXISTS users (
 *     id UUID PRIMARY KEY,
 *     first_name VARCHAR(100) NOT NULL,
 *     last_name VARCHAR(100) NOT NULL,
 *     email VARCHAR(255) NOT NULL UNIQUE,
 *     password VARCHAR(255) NOT NULL,
 *     phone_number VARCHAR(20),
 *     role VARCHAR(50) NOT NULL,
 *     is_active BOOLEAN DEFAULT TRUE,
 *     created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 *     updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
 * );
 *
 * Implements Spring Security's UserDetails so it can be used directly
 * by the authentication machinery (no separate "principal" class needed).
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class User implements UserDetails {

    @Id
    @GeneratedValue
    @Column(updatable = false, nullable = false)
    private UUID id;

    @Column(name = "first_name", nullable = false, length = 100)
    private String firstName;

    @Column(name = "last_name", nullable = false, length = 100)
    private String lastName;

    @Column(nullable = false, unique = true, length = 255)
    private String email;

    @Column(nullable = false, length = 255)
    private String password;

    @Column(name = "phone_number", length = 20)
    private String phoneNumber;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 50)
    private Role role;

    @Column(name = "is_active", nullable = false)
    @Builder.Default
    private Boolean isActive = true;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    // ---- UserDetails implementation ----

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return List.of(new SimpleGrantedAuthority("ROLE_" + role.name()));
    }

    @Override
    public String getUsername() {
        // Spring Security's notion of "username" -- we authenticate by email
        return email;
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return Boolean.TRUE.equals(isActive);
    }
}
